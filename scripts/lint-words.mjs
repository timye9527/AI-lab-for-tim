export const BANNED = [
  // 导流（最重永久封号）
  '微信', 'vx', 'VX', 'v信', '加我', '私信我', '二维码', '扫码', '链接', '网址', '公众号', '淘宝', '拼多多', '闲鱼',
  // 金融红线
  '荐股', '推荐股票', '个股推荐', '买入点', '卖出点', '目标价', '必涨', '稳赚', '保本', '保息', '翻倍', '收益率', '年化',
  '内幕', '跟单', '带单', '持仓截图', '收益截图', '理财课', '投资课',
  // 封建迷信
  '算命', '占卜', '财运', '转运', '开光', '风水', '塔罗', '运势',
  // 夸大
  '100%准', '百分百准', '最准', '科学认证', '权威测评',
];

// 这些固定说法里的词不算命中
const ALLOW = ['不构成任何投资建议'];

export function lintText(text) {
  let t = String(text);
  for (const a of ALLOW) t = t.split(a).join('');
  return BANNED.filter((w) => t.includes(w));
}
